"""Generate patient-facing explanations; never diagnose, adopt or publish a report."""
from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Any

from pydantic import BaseModel, ConfigDict, Field
from harnessing_ts.expert_collaboration import complete_json


class PatientExplanation(BaseModel):
    model_config = ConfigDict(extra="forbid")
    overview: str = Field(min_length=10, max_length=700)
    meaning: str = Field(min_length=10, max_length=900)
    uncertainty: str = Field(min_length=10, max_length=700)


def report_basis(context_id: str, labels: list[str], feature_names: list[str],
                 revision_item_id: str | None = None, policy_round_id: str | None = None,
                 analysis_round_id: str | None = None) -> dict:
    return {"contextId": context_id, "labels": sorted(set(labels)),
            "featureNames": sorted(set(feature_names)), "revisionItemId": revision_item_id,
            "policyRoundId": policy_round_id, "analysisRoundId": analysis_round_id}


async def generate_patient_report(config: Any, *, labels: list[str], features: list[dict],
                                  language: str, instructions: str = "", previous_draft: str = "",
                                  assessment_changed: bool = False) -> dict:
    # No weak truth labels, scores, expert hypotheses, cohort metrics or raw model reasoning
    # are provided to the writer. These remain in the expert workspace.
    data = {"reportLabelsSelectedForReview": labels, "attachedMeasurements": [
        {k: f.get(k) for k in ("name", "value", "unit", "judgment")} for f in features],
        "language": language, "caseAssessmentWasAdjusted": assessment_changed,
        "expertEditingRequest": instructions, "previousDraftForRewritingOnly": previous_draft}
    system = (Path(__file__).parent / "config/prompts/expert-collaboration/patient-report.md").read_text()
    raw = await complete_json(config, [{"role": "system", "content": system},
                                       {"role": "user", "content": json.dumps(data, ensure_ascii=False)}])
    explanation = PatientExplanation.model_validate(raw)
    fields = explanation.model_dump()
    text = "\n".join(fields.values())
    if re.search(r"\d", text):
        raise ValueError("Patient narrative must not introduce numeric measurements.")
    if re.search(r"已(?:经)?(?:由|经)?[^。.!?\n]{0,35}(?:审核|审阅|批准|发布|签署)|"
                 r"(?:has been|already|was)\s+(?:expert[- ]|clinician[- ])?(?:reviewed|approved|published|verified)|"
                 r"(?:expert|clinician)[- ]reviewed", text, re.IGNORECASE):
        raise ValueError("An unreviewed draft cannot claim completed review or publication.")
    if re.search(r"草稿|待审核|待审阅|待发布|\b(?:draft|unreviewed|unpublished)\b", text, re.IGNORECASE):
        raise ValueError("Report text must not embed a transient draft/publication status.")
    if set(re.findall(r"\b(?:NORM|MI|STTC|CD|HYP)\b", text)) - set(labels):
        raise ValueError("Patient narrative introduced an unselected class.")
    headings = ("本次系统发现", "这些发现意味着什么", "局限与需要确认的事项") if language == "zh" else (
        "System findings", "What these findings mean", "Limitations and uncertainty")
    safety = ("本报告由 RecursiveECG 生成，用于公开数据研究演示，不构成临床诊断或个体化治疗建议。"
              "如出现胸痛、呼吸困难或晕厥，请及时寻求紧急医疗帮助。") if language == "zh" else (
        "Generated by RecursiveECG for a public-data research demonstration, not a clinical diagnosis "
        "or individualized treatment advice. Seek urgent medical care for chest pain, breathing difficulty or fainting.")
    body = "\n\n".join(f"{heading}\n{value.strip()}" for heading, value in zip(headings, fields.values()))
    return {"note": body + "\n\n" + safety, "sections": fields, "language": language,
            "generator": "RecursiveECG", "source": "llm", "requiresExpertReview": True}
